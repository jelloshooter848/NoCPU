function keyboard(code, options = {}) { return { code, repeat: false, target: null, prevented: false, preventDefault() { this.prevented = true; }, ...options }; }
function gamepad(index, axis = 0, down = [], id = `Synthetic controller ${index}`) {
  return { index, id, mapping: 'standard', connected: true, axes: [0, axis], buttons: Array.from({ length: 16 }, (_, button) => ({ pressed: down.includes(button), value: down.includes(button) ? 1 : 0 })) };
}
function adapter(bindings = schema.cloneBindings()) {
  const events = { directions: [], axes: [], actions: [], pads: [] };
  const controls = createControls({ bindings, onDirections: (value) => events.directions.push(value), onAxes: (value) => events.axes.push(value), onAction: (value) => events.actions.push(value), onGamepads: (value) => events.pads.push(value) });
  controls.setEnabled(true); return { controls, events };
}
function memoryStorage(value = null) {
  const map = new Map(value === null ? [] : [[prefs.PREFERENCES_KEY, value]]);
  return { getItem: (key) => map.get(key) ?? null, setItem: (key, next) => map.set(key, next), removeItem: (key) => map.delete(key) };
}
function archive(data, name = 'aa.k1', level = 0) { return zipSync({ [name]: data }, { level }); }
function file(bytes, name = 'synthetic-validation.zip') { return new File([bytes], name, { type: 'application/zip' }); }
function forged(size, target) {
  // Solve the 32-bit affine CRC transform for a four-byte tail, using newly generated bytes.
  const result = new Uint8Array(size); const baseline = zip.crc32(result); const basis = [];
  for (let bit = 0; bit < 32; bit++) {
    const probe = result.slice(); probe[size - 4 + (bit >> 3)] ^= 1 << (bit & 7);
    let value = (zip.crc32(probe) ^ baseline) >>> 0; let mask = (1 << bit) >>> 0;
    for (let pivot = 31; pivot >= 0; pivot--) if ((value >>> pivot) & 1) {
      if (!basis[pivot]) { basis[pivot] = [value, mask]; break; }
      value = (value ^ basis[pivot][0]) >>> 0; mask = (mask ^ basis[pivot][1]) >>> 0;
    }
  }
  let value = (target ^ baseline) >>> 0; let solution = 0;
  for (let pivot = 31; pivot >= 0; pivot--) if ((value >>> pivot) & 1) { assert.ok(basis[pivot]); value = (value ^ basis[pivot][0]) >>> 0; solution = (solution ^ basis[pivot][1]) >>> 0; }
  assert.equal(value, 0);
  for (let bit = 0; bit < 32; bit++) if ((solution >>> bit) & 1) result[size - 4 + (bit >> 3)] ^= 1 << (bit & 7);
  assert.equal(zip.crc32(result), target >>> 0); return result;
}
function central(bytes) { const offset = bytes.length - 22; return new DataView(bytes.buffer, bytes.byteOffset).getUint32(offset + 16, true); }
function patchSize(bytes, size) { const copy = bytes.slice(); const view = new DataView(copy.buffer); view.setUint32(22, size, true); view.setUint32(central(copy) + 24, size, true); return copy; }

