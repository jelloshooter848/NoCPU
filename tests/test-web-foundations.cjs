test('an opened but unresponsive ROM store costs one read timeout per list, preserves session sets and recovers', async () => {
  let stalled = false; let reads = 0; let aborts = 0;
  const records = new Map();
  const database = {
    objectStoreNames: { contains: () => true }, close() {},
    transaction() {
      const tx = { objectStore() { return { get(key) { reads++; const request = { result: records.get(key) }; if (!stalled) queueMicrotask(() => tx.oncomplete?.()); return request; } }; }, abort() { aborts++; tx.onabort?.(); } };
      return tx;
    },
  };
  const factory = { open() { const request = { result: database }; queueMicrotask(() => request.onsuccess?.()); return request; } };
  const library = roms.createRomLibrary(factory);
  assert.equal((await library.importArchive('antiaircraft', file(archive(forged(32, 0x9de772d5))))).ok, true);
  stalled = true; const before = reads; const started = performance.now(); const entries = await library.list(); const elapsed = performance.now() - started;
  assert.equal(reads - before, 1); assert.equal(aborts, 1); assert.ok(elapsed < 5000, `list stalled for ${elapsed}ms`);
  assert.equal(entries.length, 21); assert.equal(entries.find((entry) => entry.gameId === 'antiaircraft').status, 'ready'); assert.equal(entries.find((entry) => entry.gameId === 'pong').status, 'not-required');
  assert.match(entries.find((entry) => entry.gameId === 'jetfighter').message, /unavailable/);
  stalled = false; const recovered = await library.list(); assert.equal(recovered.find((entry) => entry.gameId === 'antiaircraft').status, 'ready'); assert.equal(recovered.find((entry) => entry.gameId === 'jetfighter').message, undefined);
  records.set('jetfighter', { version: 1, gameId: 'jetfighter', fileName: 'invalid.zip', bytes: new ArrayBuffer(32) });
  const corrupt = (await library.list()).find((entry) => entry.gameId === 'jetfighter'); assert.equal(corrupt.status, 'missing'); assert.equal(corrupt.storage, 'device'); assert.equal(corrupt.archiveBytes, null); assert.equal(corrupt.fileName, null); assert.deepEqual(corrupt.members, []);
  library.close();
});
